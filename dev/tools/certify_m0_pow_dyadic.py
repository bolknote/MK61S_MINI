#!/usr/bin/env python3
"""Generate the exact root table and verify the small exponent grid for dyadic pow."""
import argparse
from concurrent.futures import ThreadPoolExecutor
from fractions import Fraction
import hashlib
import json
from math import isqrt
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'research/m0-pow-comparison-20261117'))
from midpoint_grid import FixedInterval, ceil_div

MAX_SHIFT = 116
MAX_FACTORS = 64
TAIL_SHIFT = 90
Q = 159
WORK = 320
GRID_FRACTION_BITS = 60
SEPARATION_BITS = 147
CHUNK = 1 << 20
HEADER = ROOT / 'code/native_eabi_m0_pow_dyadic_table.inc'
DOUBLE_SOURCE = 'https://www.vinc17.net/research/papers/rr_worstcases.pdf'
EXTENDED_SOURCES = (
    'https://rex-radar.inria.fr/rapportsactivite/RA2005/spaces/spaces.pdf',
    'https://perso.ens-lyon.fr/damien.stehle/downloads/randombits.pdf',
)


def ceil_sqrt(value):
    root = isqrt(value)
    return root + (root*root != value)


def roots():
    """Enclose 2^(2^-i) using successive directed integer square roots."""
    lo = hi = 2 << WORK
    result = []
    for _ in range(MAX_SHIFT):
        lo, hi = isqrt(lo << WORK), ceil_sqrt(hi << WORK)
        result.append((lo, hi))
    return result


def header(root_intervals):
    def table(name, intervals):
        digits = []
        for lo, hi in intervals:
            first, last = lo >> (WORK-Q), hi >> (WORK-Q)
            assert first == last and 1 << Q <= first < 2 << Q
            digits.append('  {' + ','.join(f'0x{(first >> (16*i))&65535:04x}' for i in range(10)) + '},')
        return ('__attribute__((section(".m0_pow_refine_data")))\n'
                f'static constexpr uint16_t {name}[][10] = {{\n' + '\n'.join(digits) + '\n};\n')

    power = 2 << (2*WORK)
    inverses = [(power//hi, ceil_div(power, lo)) for lo, hi in root_intervals]
    return ('// Generated by dev/tools/certify_m0_pow_dyadic.py.\n'
            + table('Roots', root_intervals) + '\n' + table('InverseRoots', inverses))


def published_domains(root_intervals):
    # Binary64 proof covers every nonintegral binary64 t in (-1,1).
    # Scaling recovers every subnormal, normal and overflow midpoint
    # as a subset of the 54-bit breakpoints in (1/2,2).
    assert MAX_SHIFT < 1022
    error = Fraction(6*MAX_FACTORS, 1 << Q)
    assert 2*error < Fraction(1, 1 << 112)

    # INRIA's worst directed case over [1/2,1) has this exact exponent.
    # Re-evaluate it with rational intervals. The minimum for the
    # whole grid is the published exhaustive directed-rounding result.
    grid = FixedInterval(WORK)
    index = (1 << 63) + 3990454322510295554
    assert 1 << 63 <= index < 1 << 64
    enclosure = (grid.unit, grid.unit)
    for i in range(64):
        if index & (1 << (63-i)):
            enclosure = grid.multiply(enclosure, root_intervals[i])
    step = 1 << (WORK-63)
    residue = enclosure[0] % step
    extended_gap = min(residue, step-residue-(enclosure[1]-enclosure[0]))
    assert extended_gap > 1 << (WORK-140)
    assert error < Fraction(1, 1 << 140)

    # For an increasing product, both the partial product and the
    # factor are <2; the table and one floor cost <3 units before
    # propagation by a product <2. For a decreasing product, the
    # partial product and factors are <=1. The table and the floor
    # cost <1.5 units in absolute scale. Subsequent factors only
    # contract, and putting the result on [1,2) doubles this error.
    # Thus the same 6-unit bound covers both signs.
    unit = Fraction(1, 1 << MAX_SHIFT)
    assert grid.log(2, 1)[0] > grid.unit//2
    assert error < unit / 4
    assert 2*error < Fraction(1, 1 << SEPARATION_BITS)
    assert 1074*((1 << 53)-1) < 1 << 64
    return dict(binary64={'source': DOUBLE_SOURCE, 'property': 3, 'normalized_gap_bits': 112},
                extended={'sources': EXTENDED_SOURCES, 'fraction_range': '[1/2,1)',
                          'grid_shift': 64, 'directed_gap_bits': 140})


def tail_ranges():
    # |s*y| <= 1074*(2^53-1)*2^-90. Include all midpoints whose
    # log2 magnitude could differ from that interval by <=2^-147.
    upper = Fraction(1074*((1 << 53)-1), 1 << TAIL_SHIFT)
    grid = FixedInterval(256)
    ln2_hi = Fraction(grid.log(2, 1)[1], grid.unit)
    t = (upper + Fraction(1, 1 << SEPARATION_BITS))*ln2_hi
    above = t/(1-t)
    assert 0 < t < above < Fraction(1, 1 << 26)
    return {'-': int((1 + t*(1 << 54))/2),
            '+': int((1 + above*(1 << 53))/2)}


def check_grid(executable, workers):
    ranges = tail_ranges()
    tasks = [(side, start, min(start+CHUNK, stop)) for side, stop in ranges.items()
             for start in range(0, stop, CHUNK)]
    minimum, closest, count = 1 << GRID_FRACTION_BITS, None, 0
    versions = set()

    def run(task):
        side, start, stop = task
        out = subprocess.check_output([str(executable), side, str(start), str(stop)], text=True)
        version, first, last, gap, index = out.split()
        assert (int(first), int(last)) == (start, stop) and start <= int(index) < stop
        return version, side, stop-start, int(gap), int(index)

    with ThreadPoolExecutor(max_workers=workers) as pool:
        for slice_index, row in enumerate(pool.map(run, tasks), 1):
            version, side, checked, gap, index = row
            versions.add(version)
            count += checked
            if gap < minimum:
                minimum, closest = gap, (side, index)
            if slice_index%8 == 0 or slice_index == len(tasks):
                print(f'{count} midpoints', flush=True)
    assert count == sum(ranges.values()) and len(versions) == 1 and closest is not None
    assert minimum > 1 << (MAX_SHIFT+GRID_FRACTION_BITS-SEPARATION_BITS)
    return dict(checked=count, ranges=ranges, mpfr=versions.pop(), closest=closest,
                minimum_gap_units=minimum, unit_exponent=-MAX_SHIFT-GRID_FRACTION_BITS,
                strict_log2_gap=f'2^-{SEPARATION_BITS}', exponent_magnitude_limit='2^-37',
                minimum_unreduced_exponent_denominator_shift=TAIL_SHIFT)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header', type=Path, help='write the generated root table')
    parser.add_argument('--grid', type=Path, help='compiled m0_pow_dyadic_grid.c checker')
    parser.add_argument('--json', type=Path, help='write an exhaustive certificate')
    parser.add_argument('--workers', type=int, default=1)
    args = parser.parse_args()
    if not __debug__:
        raise RuntimeError('Enable Python assertions to verify the certificate')
    if bool(args.grid) != bool(args.json):
        parser.error('--grid and --json are required together')

    root_intervals = roots()
    generated = header(root_intervals)
    published = published_domains(root_intervals)
    if args.header:
        args.header.write_text(generated)
    assert HEADER.read_text() == generated
    if args.grid:
        tail = check_grid(args.grid.resolve(), args.workers)
        paths = (HEADER, Path(__file__), ROOT/'dev/tools/m0_pow_dyadic_grid.c',
                 ROOT/'code/native_eabi_m0_pow_dyadic.inc',
                 ROOT/'code/native_eabi_m0_pow_power_bounds.inc',
                 ROOT/'code/native_eabi_m0_cr.cpp')
        hashes = {str(path.relative_to(ROOT)):hashlib.sha256(path.read_bytes()).hexdigest()
                  for path in paths}
        json_report = dict(status='PASS_DYADIC_POW_DOMAINS', published_domains=published,
                           tail_grid=tail, interval_width_q159=6*MAX_FACTORS,
                           maximum_full_products=MAX_FACTORS, source_sha256=hashes)
        args.json.write_text(json.dumps(json_report, indent=2)+'\n')
        print(json_report['status'], tail['strict_log2_gap'])


if __name__ == '__main__':
    main()
