#!/usr/bin/env python3
"""Generate the F401 text bitstream; firmware builds use committed data only."""
from pathlib import Path
import argparse,ast,collections,heapq,importlib.util,json,re
ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('m8',ROOT/'dev/lib/m8_codec.py');m8=importlib.util.module_from_spec(spec);spec.loader.exec_module(m8)
PATTERN=re.compile(r'\b(PT|MP8)\(\s*("(?:[^"\\]|\\.)*")\s*\)')
def arrays(name,values):
    lines=[f'static const uint8_t {name}[] = {{']
    lines += ['  '+','.join(str(x) for x in values[i:i+20])+',' for i in range(0,len(values),20)]
    return '\n'.join(lines+['};'])+'\n'
def pack9(values):
    out=bytearray((len(values)*9+7)//8+1)
    for i,v in enumerate(values):
        bit=i*9;part=v<<(bit%8);out[bit//8]|=part&255;out[bit//8+1]|=(part>>8)&255
    return out

def generate():
    messages={}
    for path in sorted((ROOT/'code').glob('*')):
        if path.suffix not in ('.cpp','.hpp','.h','.inc','.ino'):continue
        for kind,literal in PATTERN.findall(path.read_text()):
            text=ast.literal_eval(literal);messages[kind=='MP8',text]=(m8.encode(text) if kind=='MP8' else text.encode())+b'\0'
    if not messages:messages[False,'']=b'\0'
    keys=sorted(messages);sequences=[list(messages[key]) for key in keys];pairs=[]
    for token in range(256,384):
        frequencies=collections.Counter((seq[i],seq[i+1]) for seq in sequences for i in range(len(seq)-1))
        if not frequencies:break
        pair,count=min(frequencies.items(),key=lambda item:(-item[1],item[0]))
        if count<4:break
        pairs.append(pair);next_sequences=[]
        for seq in sequences:
            out=[];i=0
            while i<len(seq):
                if i+1<len(seq) and (seq[i],seq[i+1])==pair:out.append(token);i+=2
                else:out.append(seq[i]);i+=1
            next_sequences.append(out)
        sequences=next_sequences
    frequencies=collections.Counter(t for seq in sequences for t in seq)
    heap=[];serial=0
    for token,count in sorted(frequencies.items()):heapq.heappush(heap,(count,serial,token));serial+=1
    while len(heap)>1:
        a,_,left=heapq.heappop(heap);b,_,right=heapq.heappop(heap)
        heapq.heappush(heap,(a+b,serial,(left,right)));serial+=1
    lengths={}
    def visit(node,depth):
        if isinstance(node,int):lengths[node]=max(1,depth)
        else:visit(node[0],depth+1);visit(node[1],depth+1)
    visit(heap[0][2],0);ordered=sorted(lengths,key=lambda t:(lengths[t],t));maximum=max(lengths.values())
    assert maximum<32
    counts=[sum(lengths[t]==i for t in ordered) for i in range(maximum+1)];assert max(counts)<256
    codes={};code=0;previous=0
    for token in ordered:
        code<<=lengths[token]-previous;codes[token]=(code,lengths[token]);code+=1;previous=lengths[token]
    bits=[];offsets=[]
    for seq in sequences:
        offsets.append(len(bits))
        for token in seq:
            code,width=codes[token];bits.extend((code>>i)&1 for i in range(width-1,-1,-1))
    assert len(bits)<65535,"packed text must fit the reserved pointer range"
    data=bytearray((len(bits)+7)//8)
    for i,bit in enumerate(bits):data[i//8]|=bit<<(7-i%8)
    depths={i:0 for i in range(256)}
    for i,pair in enumerate(pairs,256):depths[i]=1+max(depths[t] for t in pair)
    depth=max(depths.values())
    catalog=['// Generated by dev/tools/pack_resident_text.py.\n',f'constexpr unsigned MAX_PAIR_DEPTH={depth}, MAX_LITERAL_BYTES={max(len(v) for v in messages.values())};\n',
             'constexpr unsigned INVALID_OFFSET=~0U;\nstruct LiteralEntry {const char* text;unsigned offset;bool m8;};\n',
             'constexpr LiteralEntry LITERALS[] = {\n']
    for key,offset in zip(keys,offsets):catalog.append('  {'+json.dumps(key[1],ensure_ascii=False)+','+str(offset)+','+str(key[0]).lower()+'},\n')
    catalog += ['};\nconstexpr bool equal_literal(const char* a,const char* b) {while(*a&&*a==*b){++a;++b;}return *a==*b;}\n',
                'constexpr unsigned literal_offset(const char* text,bool m8) {for(const auto& item:LITERALS)if(item.m8==m8&&equal_literal(item.text,text))return item.offset;return INVALID_OFFSET;}\n']
    runtime='// Generated by dev/tools/pack_resident_text.py.\n'+f'constexpr unsigned MAX_CODE_BITS={maximum};\n'
    runtime+=arrays('CODE_COUNTS',counts)+arrays('CODE_SYMBOLS',pack9(ordered))+arrays('PAIR_SYMBOLS',pack9([v for pair in pairs for v in pair]))+arrays('MESSAGE_BITS',data)
    return {ROOT/'code/packed_text_catalog.inc':''.join(catalog),ROOT/'code/packed_text_data.inc':runtime},sum(len(v) for v in messages.values()),len(data)+len(pack9(ordered))+len(pack9([v for p in pairs for v in p]))+len(counts)

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs,raw,stored=generate()
    for path,text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit(f'{path}: regenerate packed text')
        else:path.write_text(text)
    print(f'Packed text: literals {raw} -> {stored} bytes (decoder and caller code measured separately)')
if __name__=='__main__':main()
