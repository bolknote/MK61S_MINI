#!/usr/bin/env python3
"""Check the fixed-work logarithmic pow comparison and its close-to-one domain."""
import argparse
from fractions import Fraction as F
import hashlib
import json
from math import ceil
from pathlib import Path
import sys

from certify_m0_pow_close_one import down, sqrt_bounds, up, SOURCE_URL

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'research/m0-pow-comparison-20261117'))
from midpoint_grid import FixedInterval

P = 16384
WORDS = P//16
TABLE_LAST = 16
SINGLES = 256
RESIDUAL = P//2
FIRST_BLOCK = SINGLES+7
BLOCKS = (P-SINGLES-RESIDUAL)//7+1
GROUPS = P//(TABLE_LAST+1)
GUARD = 83
GAP = P-GUARD-1
HEADER = ROOT/'code/native_eabi_m0_pow_log_side_table.inc'


def table():
    grid = FixedInterval(P+64)
    ratios = [(2,1)]+[(1<<i,(1<<i)-1) for i in range(2,TABLE_LAST+1)]
    rows = []
    for a,b in ratios:
        lo,hi = grid.log(a,b)
        value = lo>>64
        assert value == hi>>64 and 0 < value < 1 << P
        words = [f'0x{(value >> (16*i))&65535:04x}' for i in range(WORDS)]
        rows.append('  {\n'+'\n'.join('    '+','.join(words[i:i+16])+','
                                     for i in range(0,WORDS,16))+'\n  },')
    return ('// Generated by dev/tools/certify_m0_pow_log_side.py.\n'
            '#if defined(__arm__) || defined(__thumb__)\n'
            '__attribute__((section(".m0_pow_log_table")))\n'
            '#endif\nstatic constexpr Word LogFactors[][Words] = {\n'
            +'\n'.join(rows)+'\n};\n')


def arithmetic():
    # For a leading bit j, a single factor subtracts at least 2^(j-1)
    # and at most 3/4 of the residual plus one unit. There can be at
    # most two visits to the same j.
    assert (1 << (P-SINGLES))//4 > 1
    # For an 8-bit factor put H=2^(j-7) and c=floor(D/H)-1. The part
    # above c*H is at least H and below 2*H. The additional subtraction
    # is at most c*(D/S)*H+c, strictly below H.
    assert F(254, 1 << (SINGLES-1))+F(254, 1 << (RESIDUAL-7)) < 1
    # The reduced leading bit drops by at least 7, which also makes
    # consecutive block shifts differ by at least 7.
    single_factors = 2*(SINGLES-1)
    factors = single_factors+BLOCKS
    assert BLOCKS == 1134 and FIRST_BLOCK == 263
    max_power = P//(FIRST_BLOCK-8)
    assert max_power == 64 and max_power*8 <= 16*32
    # Input displacement, rounded shifts, negative-power floors,
    # omitted series tails, table floors and grouped divisions.
    reduction_error = single_factors+254*BLOCKS
    error = reduction_error+1 + factors + BLOCKS*max_power+2*(TABLE_LAST-1)+GROUPS+1075
    assert error < 1 << 19
    assert error*((1 << 63)+1)+1 < 1 << GUARD
    # In the initial exact scaled mantissa leading width is at most
    # 53 fractional bits. Only the residual words before the integer
    # one are filled. All shifted ranges read at most Words+2 words.
    assert (53+15)//16==4 and 7<16
    # For grouped j, single terms sum to <4*2^-17j. Block factors
    # are <2^-255 and separated in shift by 7. Their sum is smaller
    # than 2*2^-255j. This bounds the prefix division length.
    assert FIRST_BLOCK-8 > TABLE_LAST+1
    assert F(1)/(1-F(1,1 << 7)) < 2
    assert GROUPS*(1 << 16) < 1 << 32
    work = dict(
        reduction_word_updates=single_factors*WORDS+BLOCKS*WORDS,
        limb_divisions=sum((P-n*(TABLE_LAST+1)+2)//16+1 for n in range(2,GROUPS+1)),
        single_factor_group_inserts=sum(max(0,min(SINGLES,P//n)-TABLE_LAST)
                                      for n in range(1,GROUPS+1)),
        block_power_limb_products=sum(
            min(BLOCKS,max(0,(P//n+8-FIRST_BLOCK)//7+1)) *
            sum(max(1,(8*k+15)//16) for k in range(n))
            for n in range(1,max_power+1)))
    return dict(precision=P,error_units_upper=error,comparison_guard_bits=GUARD,
                unresolved_gap=f'2^-{GAP}', maximum_factors=dict(single=single_factors,blocks=BLOCKS),
                maximum_selected_operations_per_log=work)


def close_one():
    """Laurent's real two-log bound, with outward rational parameters."""
    grid = FixedInterval(256)
    lnlo, lnhi = (F(x,grid.unit) for x in grid.log(2,1))
    distance_bits = 27
    d = F(1,1 << distance_bits)
    log_limit = d/(1-d)
    assert (1-d) > F(1,2) and (1+d) < 2
    assert F(1,(1<<52)+1) > F(1,1<<53)
    assert F(1,(1<<53)+1) > F(1,1<<54)
    epsilon = F(1,1 << 62)
    assert F(1,1<<GAP) < epsilon
    assert F(1,1<<54)-epsilon > F(1,1<<55)
    assert log_limit+epsilon < 2*d
    assert d/(1+d)-log_limit/2 > d/4 > epsilon
    # Consequently |y*ln(x)|>2^-55 and |y|>2^(27-56) for an
    # unresolved comparison. The reduced denominator is <=2^81.
    maximum_shift = 108-distance_bits
    maximum_sum = (1 << maximum_shift)+(1 << 53)

    mu = F(5,12)
    sigma = (1+2*mu-mu*mu)/2
    rho_shift, a, h = 29,F(79),F(57)
    assert F(1,3)<=mu<=1
    assert (1 << rho_shift)*log_limit+108*lnhi < a
    lambda_lo = down(sigma*rho_shift*lnlo)
    lambda_hi = up(sigma*rho_shift*lnhi)
    assert 0 < lambda_lo < lambda_hi < h and a*a>lambda_hi*lambda_hi and lnhi/2<h
    assert F(maximum_sum)*lambda_hi/a < 1 << 79
    assert 79*lnhi+F(181,100)<h
    H = down(h/lambda_hi+1/sigma)
    root = sqrt_bounds(1+1/(4*H*H))[1]
    omega,theta = up(2*(1+root)), up(root+1/(2*H))
    omega54 = sqrt_bounds(sqrt_bounds(omega**5)[1])[1]
    theta14 = sqrt_bounds(sqrt_bounds(theta)[1])[1]
    inner = up(omega*omega/9+8*lambda_hi*omega54*theta14/(3*a*sqrt_bounds(H)[0])+
               F(8,3)*lambda_hi*omega/(a*H))
    C = up(mu/(lambda_lo**3*sigma)*(omega/6+sqrt_bounds(inner)[1]/2)**2)
    Cprime = sqrt_bounds(C*sigma*omega*theta/(lambda_lo**3*mu))[1]
    z = up(h+rho_shift*lnhi)
    assert Cprime*z*z*a*a < 1 << 15
    loss = ceil(up(C*z*z*a*a+sqrt_bounds(omega*theta)[1]*z+15*lnhi))
    separation_bits = int(F(loss)/lnlo)+maximum_shift+1
    assert separation_bits*lnlo > loss+maximum_shift*lnhi
    assert separation_bits < GAP
    # Odd coefficients at a tie fit the existing exact 8192-bit pass.
    # The lower gap for a nonzero dependent case was proved separately.
    assert 1728 < 8192 and 170 < GAP
    return dict(reference=SOURCE_URL, theorem='Theorem 2', parameters=dict(
                    rho_shift=rho_shift, a=int(a), h=int(h), mu=str(mu)),
                maximum_base_displacement=f'2^-{distance_bits}', maximum_abs_y_within_input_domain='1/2',
                positive_base_encodings=3*(1 << (52-distance_bits))+1,
                nonzero_log_gap=f'2^-{separation_bits}', loss_nats=loss,
                maximum_q_exponent=maximum_shift)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--header',type=Path,help='write generated table')
    parser.add_argument('--json',type=Path)
    args = parser.parse_args()
    if not __debug__:
        raise RuntimeError('Enable Python assertions to verify the certificate')
    rules = arithmetic()
    domain = close_one()
    generated = table()
    if args.header:
        args.header.write_text(generated)
    assert HEADER.read_text() == generated
    if args.json:
        sources = (Path(__file__),HEADER,ROOT/'code/native_eabi_m0_pow_log_side.inc',
                   ROOT/'code/native_eabi_m0_pow_power_bounds.inc',ROOT/'code/native_eabi_m0_cr.cpp')
        args.json.write_text(json.dumps(dict(status='PASS_LOG_SIDE', arithmetic=rules, close_one=domain,
            practical_uniform_latency_established=False, source_sha256={
                str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sources}),
            indent=2)+'\n')
    print('PASS_LOG_SIDE',rules,domain)


if __name__=='__main__':
    main()
