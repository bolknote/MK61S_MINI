#!/usr/bin/env python3
"""Generate dyadic-center coefficients for the RP2040 exp residual."""
import argparse
from fractions import Fraction as F
from pathlib import Path


def coefficients():
    for i in range(1470):
        c = F(i, 1 << 21)
        term = F(1)
        even = odd = F(0)
        for n in range(1, 11):
            term = term*c/n
            if n >= 3:
                if n&1:
                    odd += term
                else:
                    even += term
        error = term*c/11/(1-c/12)
        # The runtime computes the dominant square. Store the even terms
        # from degree four and the full odd part starting at degree three.
        e = round(even*(1 << 68))
        o = round(odd*(1 << 69))
        assert abs(F(e,1 << 68)-even)+error <= F(1,1 << 69)
        assert abs(F(o,1 << 69)-odd)+error <= F(1,1 << 70)
        assert 0 <= e < 1 << 22 and 0 <= o < 1 << 36
        yield o&0xffffffff, e|((o >> 32) << 22)


def render():
    rows = [f'  {{{lo}U, {hi}U}},' for lo,hi in coefficients()]
    return ('// Generated by dev/tools/generate_m0_exp_center.py.\n'
            'static constexpr uint32_t exp_center[1470][2] MK61_M0_EXP_CENTER_TABLE={\n'
            + '\n'.join(rows) + '\n};\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    args.output.write_text(render())


if __name__ == '__main__':
    main()
