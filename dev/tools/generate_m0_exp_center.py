#!/usr/bin/env python3
"""Generate dyadic-center coefficients for the RP2040 exp residual."""
import argparse
from fractions import Fraction as F
from pathlib import Path
import re


def coefficients():
    for i in range(1470):
        c = F(i, 1 << 21)
        term = F(1)
        even = odd = F(0)
        for n in range(1, 11):
            term = term*c/n
            if n >= 3:
                if n&1:
                    odd += term
                else:
                    even += term
        error = term*c/11/(1-c/12)
        # The runtime computes the dominant square. Store the even terms
        # from degree four and the full odd part starting at degree three.
        e = round(even*(1 << 68))
        o = round(odd*(1 << 69))
        assert abs(F(e,1 << 68)-even)+error <= F(1,1 << 69)
        assert abs(F(o,1 << 69)-odd)+error <= F(1,1 << 70)
        assert 0 <= e < 1 << 22 and 0 <= o < 1 << 36
        yield o&0xffffffff, e|((o >> 32) << 22)


def render():
    rows = [f'  {{{lo}U, {hi}U}},' for lo,hi in coefficients()]
    return ('// Generated by dev/tools/generate_m0_exp_center.py.\n'
            'static constexpr uint32_t exp_center[1470][2] MK61_M0_EXP_CENTER_TABLE={\n'
            + '\n'.join(rows) + '\n};\n')


def refine_rows(root):
    text = (root / 'code/native_eabi_m0_refine_table.inc').read_text()
    block = text.split('refine_exp_table[512][3]={', 1)[1].split('};', 1)[0]
    rows = [tuple(map(int, m)) for m in re.findall(r'\{(\d+)U,(\d+)U,(\d+)U\}', block)]
    assert len(rows) == 512
    return rows


def render_scale(rows):
    packed_rows = []
    for _, middle, hi in rows:
        assert 1 << 30 <= hi < 1 << 31
        packed_rows.append(f'  {{{middle}U, {hi}U}},')
    return ('// Generated by dev/tools/generate_m0_exp_center.py from the Q94 scale.\n'
            'static constexpr uint32_t exp_center_scale[512][2] '
            '__attribute__((section(".m0_exp_scale_table"),aligned(8)))={\n'
            + '\n'.join(packed_rows) + '\n};\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--scale-output', type=Path)
    args = p.parse_args()
    args.output.write_text(render())
    if args.scale_output:
        root = Path(__file__).resolve().parents[2]
        args.scale_output.write_text(render_scale(refine_rows(root)))


if __name__ == '__main__':
    main()
