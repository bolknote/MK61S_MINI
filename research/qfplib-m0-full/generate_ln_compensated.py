"""Certify compact rounding-error compensation data for the Qfplib ln fork."""
import argparse
from fractions import Fraction as F
import hashlib
import json
from pathlib import Path

from generate_ln_constants import generate

ROOT=Path(__file__).resolve().parent


def nearest(q):
    n,r=divmod(q.numerator,q.denominator)
    return n+(2*r>q.denominator or 2*r==q.denominator and n&1)


def generate_compensation():
    _,original=generate()
    rows=[]
    for row in original['certificates'][:19]:
        v82=int(row['value_Q245'],16)>>(245-82)
        v62=int(row['upstream_Q62_nearest'],16)
        delta=(v62<<20)-v82
        assert -(1<<19)<=delta<=1<<19
        rows.append((v62,delta))
    reciprocal=[]
    maximum=F(0)
    for index in range(384,512):
        # x after an accepted greedy step is in [3/4,1).
        r=nearest(F(1<<20,2*index+1))
        assert 1024<=r<1366
        for endpoint in [F(index,512),F(index+1,512)]:
            maximum=max(maximum,abs(F(r,1024)-1/endpoint))
        reciprocal.append(r)
    assert maximum<=F(41,18432)
    text=['@ SPDX-License-Identifier: GPL-2.0-only',
          '@ Generated by generate_ln_compensated.py; exact rational certificates.',
          f'.set lncomp_delta2, {rows[0][1]}',
          '.macro lncomp_steps']
    text += [f' lncomp_step {i},0x{v&0xffffffff:08x},0x{v>>32:08x},{d}'
             for i,(v,d) in enumerate(rows[1:],1)]
    text += ['.endm','.macro lncomp_reciprocal_data','.align 2','.Llncomp_recip:']
    text += [' .hword '+','.join(map(str,reciprocal[i:i+8])) for i in range(0,128,8)]
    text += ['.endm']
    output='\n'.join(text)+'\n'
    report=dict(status='PASS',greedy_steps=18,precision=82,
                embedded_log_rows_bytes=18*12,reciprocal_table_bytes=256,
                data_bytes=472,reciprocal_error_bound=str(maximum),
                ln2_delta_Q20=rows[0][1],log_rows=[dict(index=i,nearest_Q62=hex(v),delta_Q20=d) for i,(v,d) in enumerate(rows)],
                reciprocal_Q10=reciprocal,sha256=hashlib.sha256(output.encode()).hexdigest())
    return output,report


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=ROOT/'src/ln_comp_constants.inc')
    p.add_argument('--json',type=Path,required=True);p.add_argument('--check',action='store_true')
    args=p.parse_args();text,report=generate_compensation()
    if args.check:assert args.output.read_text()==text
    else:args.output.write_text(text)
    args.json.parent.mkdir(parents=True,exist_ok=True)
    args.json.write_text(json.dumps(report,indent=2)+'\n')
    print('PASS: 472-byte ln compensation constants')
