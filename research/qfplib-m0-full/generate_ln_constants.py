"""Certify small logarithm constants using exact rational atanh bounds."""
import argparse
from fractions import Fraction as F
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parent


def log_bounds(numerator, denominator, precision):
    z=F(numerator-denominator,numerator+denominator)
    assert 0<z<1
    square=z*z
    power=z
    total=F(0)
    for k in range(1,precision+2):
        total+=power/(2*k-1)
        power*=square
        error=2*power/((2*k+1)*(1-square))
        lo,hi=2*total,2*total+error
        scale=1<<precision
        lower=lo.numerator*scale//lo.denominator
        upper=hi.numerator*scale//hi.denominator
        if lower==upper:return lower,lo,hi,k
    raise AssertionError('rational logarithm interval did not decide constant')


def generate():
    rows=[];certificates=[]
    # Rows1..24 are log(1+2^-i); row0 is ln2. Values are floored at Q245.
    inputs=[(2,1)]+[((1<<i)+1,1<<i) for i in range(1,25)]
    original=(ROOT/'upstream/qfplib-m0-full_gcc.S').read_text()
    words=re.findall(r'\.word\s+(0x[\da-f]+),\s*(0x[\da-f]+)',original.split('\ndtab_exp:\n')[1])
    for i,(n,d) in enumerate(inputs):
        v,lo,hi,terms=log_bounds(n,d,245)
        rows.append([v>>(32*j)&0xffffffff for j in range(8)])
        nearest_lo=(lo*(1<<62)+F(1,2)).numerator//(lo*(1<<62)+F(1,2)).denominator
        nearest_hi=(hi*(1<<62)+F(1,2)).numerator//(hi*(1<<62)+F(1,2)).denominator
        assert nearest_lo==nearest_hi
        old=0x2c5c85fdf473de6b if i==0 else int(words[i-1][0],16)+(int(words[i-1][1],16)<<32)
        assert old==nearest_lo,(i,hex(old),hex(nearest_lo))
        certificates.append(dict(index=i,terms=terms,value_Q245=hex(v),upstream_Q62_nearest=hex(old)))
    lines=['/* SPDX-License-Identifier: GPL-2.0-only */',
           '/* Generated by generate_ln_constants.py; exact rational bounds. */',
           'static const uint32_t ln245[25][8] = {']
    lines.extend('  {'+', '.join(f'0x{v:08x}u' for v in row)+'},' for row in rows)
    lines.append('};')
    text='\n'.join(lines)+'\n'
    return text,dict(status='PASS',precision=245,rows=25,bytes=800,
                     certificates=certificates,sha256=hashlib.sha256(text.encode()).hexdigest())


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=ROOT/'src/ln_constants.inc')
    p.add_argument('--json',type=Path,required=True)
    p.add_argument('--check',action='store_true')
    args=p.parse_args();text,report=generate()
    if args.check:assert args.output.read_text()==text
    else:args.output.write_text(text)
    args.json.parent.mkdir(parents=True,exist_ok=True)
    args.json.write_text(json.dumps(report,indent=2)+'\n')
    print('PASS: 800-byte Q245 log constants and original Q62 rounding')
