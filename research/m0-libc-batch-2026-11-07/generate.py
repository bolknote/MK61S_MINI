#!/usr/bin/env python3
"""Generate the shared opt-in Thumb-1 bodies for the complete eight-function batch."""
from pathlib import Path
import json
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
FUNCTIONS=['strlen','strcmp','strncmp','memcmp','strnlen','strcpy','strncpy','strncat']
SIGNATURES=[('size_t','const char* text'),('int','const char* left,const char* right'),
 ('int','const char* left,const char* right,size_t count'),('int','const void* left,const void* right,size_t count'),
 ('size_t','const char* text,size_t maximum'),('char*','char* destination,const char* source'),
 ('char*','char* destination,const char* source,size_t count'),('char*','char* destination,const char* source,size_t count')]
def asm(lines):return '\n'.join(json.dumps(line+'\n') for line in lines)+'\n'
def steps(make):
    out=[]
    for i in range(4):
        if i:out.append('#if MK61_M0_LIBC_CURRENT >= %d'%(2 if i==1 else 4))
        out+=asm(make(i)).splitlines()
        if i:out.append('#endif')
    return out
def generate_byte():
    out=['/* Generated by research/m0-libc-batch-2026-11-07/generate.py. */','".syntax unified\\n"']
    for op in range(8):
        out+=['#%s MK61_M0_LIBC_OPERATION == %d'%('if' if op==0 else 'elif',op)]
        if op==0:
            out+=asm(['mov r1,r0','1:']).splitlines()
            out+=steps(lambda i:['ldrb r2,[r0,#%d]'%i,'cmp r2,#0','beq %df'%(10+i)])
            out+=['"adds r0,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"b 1b\\n"']
            for i in [3,2,1]:
                out+=['#if MK61_M0_LIBC_CURRENT >= %d'%(2 if i==1 else 4)]+asm(['%d: adds r0,#1'%(10+i)]).splitlines()+['#endif']
            out+=asm(['10: subs r0,r0,r1','bx lr']).splitlines()
        elif op in (1,2,3):
            bounded=op in (2,3)
            out+=asm((['cmp r2,#0','beq 9f','push {r4}'] if bounded else [])+['1:']).splitlines()
            def step(i):
                left,right=('r3','r4') if bounded else ('r2','r3')
                a=['ldrb %s,[r0,#%d]'%(left,i),'ldrb %s,[r1,#%d]'%(right,i),'subs %s,%s,%s'%(left,left,right),'bne 8f']
                if op!=3:a+=['cmp %s,#0'%right,'beq 8f']
                if bounded:a+=['subs r2,#1','beq 8f']
                return a
            out+=steps(step)
            out+=['"adds r0,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"adds r1,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"b 1b\\n"']
            out+=asm(['8: mov r0,%s'%('r3' if bounded else 'r2'),*(['pop {r4}'] if bounded else []),'bx lr',*(['9: movs r0,#0','bx lr'] if bounded else [])]).splitlines()
        elif op==4:
            out+=asm(['movs r3,#0','cmp r1,#0','beq 10f','1:']).splitlines()
            out+=steps(lambda i:['ldrb r2,[r0,#%d]'%i,'cmp r2,#0','beq %df'%(10+i),'subs r1,#1','beq %df'%(11+i)])
            out+=['"adds r0,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"adds r3,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"b 1b\\n"']
            for i in [4,3,2,1]:
                out+=['#if MK61_M0_LIBC_CURRENT >= %d'%(4 if i>=3 else 2 if i==2 else 1)]+asm(['%d: adds r3,#1'%(10+i)]).splitlines()+['#endif']
            out+=asm(['10: mov r0,r3','bx lr']).splitlines()
        elif op==5:
            out+=asm(['mov r3,r0','1:']).splitlines()
            out+=steps(lambda i:['ldrb r2,[r1,#%d]'%i,'strb r2,[r3,#%d]'%i,'cmp r2,#0','beq 9f'])
            out+=['"adds r1,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"adds r3,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"']+asm(['b 1b','9: bx lr']).splitlines()
        elif op==6:
            out+=asm(['mov r12,r0','cmp r2,#0','beq 9f','1:']).splitlines()
            out+=steps(lambda i:['ldrb r3,[r1,#%d]'%i,'strb r3,[r0,#%d]'%i,'subs r2,#1','beq 9f','cmp r3,#0','beq %df'%(10+i)])
            out+=['"adds r0,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"adds r1,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"b 1b\\n"']
            for i in range(4):
                out+=['#if MK61_M0_LIBC_CURRENT >= %d'%(4 if i>=2 else 2 if i==1 else 1)]+asm(['%d: adds r0,#%d'%(10+i,i+1),'b 2f']).splitlines()+['#endif']
            out+=asm(['2: cmp r2,#4','blo 3f','mov r1,r0','lsls r1,r1,#30','beq 4f','strb r3,[r0]','adds r0,#1','subs r2,#1','b 2b','4: str r3,[r0]','adds r0,#4','subs r2,#4','b 2b','3: cmp r2,#0','beq 9f','strb r3,[r0]','adds r0,#1','subs r2,#1','b 3b','9: mov r0,r12','bx lr']).splitlines()
        else:
            out+=asm(['mov r12,r0','cmp r2,#0','beq 9f','1:']).splitlines()
            out+=steps(lambda i:['ldrb r3,[r0,#%d]'%i,'cmp r3,#0','beq %df'%(10+i)])
            out+=['"adds r0,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"b 1b\\n"']
            for i in range(4):
                out+=['#if MK61_M0_LIBC_CURRENT >= %d'%(4 if i>=2 else 2 if i==1 else 1)]+asm(['%d:'%(10+i),*(['adds r0,#%d'%i] if i else []),'b 2f']).splitlines()+['#endif']
            out+=['"2:\\n"']
            out+=steps(lambda i:['ldrb r3,[r1,#%d]'%i,'strb r3,[r0,#%d]'%i,'cmp r3,#0','beq 9f','subs r2,#1','beq %df'%(20+i)])
            out+=['"adds r0,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"adds r1,#" MK61_M0_LIBC_STR(MK61_M0_LIBC_CURRENT) "\\n"','"b 2b\\n"']
            for i in range(4):
                out+=['#if MK61_M0_LIBC_CURRENT >= %d'%(4 if i>=2 else 2 if i==1 else 1)]+asm(['%d: adds r0,#%d'%(20+i,i+1),'b 3f']).splitlines()+['#endif']
            out+=asm(['3: movs r3,#0','strb r3,[r0]','9: mov r0,r12','bx lr']).splitlines()
    out+=['#endif'];(ROOT/'code/libc_m0_byte.inc').write_text('\n'.join(out)+'\n')
def generate_header():
    lines=['/* All eight M0+ candidates are opt-in until the grouped hardware verdict.',' * 0 keeps the existing implementation; 1/2/4 are ordered byte unrolls;',' * 8/16 select checked, naturally aligned word candidates for all eight.',' * This is one shared body source for native, SDK and isolated controls. */',
     '#ifndef MK61_MEMORY_LIBC_M0_H','#define MK61_MEMORY_LIBC_M0_H','#include <stddef.h>','#include <stdint.h>',
     '#ifndef MK61_M0_LIBC_UNROLL','#define MK61_M0_LIBC_UNROLL 0','#endif',
     '#if MK61_M0_LIBC_UNROLL != 0 && MK61_M0_LIBC_UNROLL != 1 && MK61_M0_LIBC_UNROLL != 2 && MK61_M0_LIBC_UNROLL != 4 && MK61_M0_LIBC_UNROLL != 8 && MK61_M0_LIBC_UNROLL != 16','#error "Unsupported M0 libc candidate"','#endif',
     '#if defined(__ARM_ARCH_6M__) && defined(__GNUC__) && !defined(__clang__)',
     '/* Inline helpers must inherit the same options as their public entries. */',
     '#pragma GCC push_options','#pragma GCC optimize ("Os", "no-tree-loop-distribute-patterns")',
     '#define MK61_M0_LIBC_STR_INNER(v) #v','#define MK61_M0_LIBC_STR(v) MK61_M0_LIBC_STR_INNER(v)']
    for index,name in enumerate(FUNCTIONS):
        key='MK61_M0_'+name.upper()+'_IMPL';default='MK61_M0_LIBC_UNROLL'
        lines+=['#ifndef '+key]
        lines+=['#if defined(MK61_APP_SHARED_RUNTIME) && '+str(int(name in ['strlen','strncmp','memcmp','strncat'])),'#define '+key+' 0']
        lines+=['#else','#define '+key+' '+default,'#endif','#endif']
        allowed=[0,1,2,4,8,16]
        lines+=['#if '+' && '.join(key+' != '+str(v) for v in allowed),'#error "Unsupported '+name+' candidate"','#endif','#if '+key,'#define MK61_ARM_'+name.upper()+' 1','#define MK61_M0_LIBC_OPERATION '+str(index),'#define MK61_M0_LIBC_CURRENT '+key]
        if index in [1,2]:lines+=['#if '+key+' >= 8','#include "libc_m0_compare.h"','__attribute__((noipa,aligned(16),optimize("Os")))',SIGNATURES[index][0]+' '+name+'('+SIGNATURES[index][1]+') {','  return mk61_m0_compare_words(left,right,'+('0,0' if index==1 else 'count,1')+', '+key+' == 16 ? 2 : 1);','}','#else']
        if index>=4:
            expression='mk61_m0_length_words(text,maximum,1,'+key+' == 16 ? 2 : 1)' if index==4 else 'mk61_m0_copy_words(destination,source,'+('0,0' if index==5 else 'count,'+str(1 if index==6 else 2))+','+key+' == 16 ? 2 : 1)'
            lines+=['#if '+key+' >= 8','#include "libc_m0_copy_words.h"','__attribute__((noipa,aligned(16),optimize("Os","no-tree-loop-distribute-patterns")))',SIGNATURES[index][0]+' '+name+'('+SIGNATURES[index][1]+') {','  return '+expression+';','}','#else']
        params=SIGNATURES[index][1].replace(' text',' text __attribute__((unused))').replace(' left',' left __attribute__((unused))').replace(' right',' right __attribute__((unused))').replace(' count',' count __attribute__((unused))').replace(' maximum',' maximum __attribute__((unused))').replace(' destination',' destination __attribute__((unused))').replace(' source',' source __attribute__((unused))')
        lines+=['__attribute__((naked,noipa,aligned(16)))',SIGNATURES[index][0]+' '+name+'('+params+') {','  __asm__(']
        if index in [0,3]:lines+=['#if '+key+' >= 8','#include "libc_m0_'+('strlen' if index==0 else 'memcmp')+'_word.inc"','#else']
        lines+=['#include "libc_m0_byte.inc"']
        if index in [0,3]:lines+=['#endif']
        lines+=['  );','}']
        if index in [1,2] or index>=4:lines+=['#endif']
        lines+=['#undef MK61_M0_LIBC_CURRENT','#undef MK61_M0_LIBC_OPERATION','#endif']
    lines+=['#undef MK61_M0_LIBC_STR','#undef MK61_M0_LIBC_STR_INNER','#pragma GCC pop_options','#endif','#endif'];(ROOT/'code/memory_libc_m0.h').write_text('\n'.join(lines)+'\n')
def main():
    generate_byte();generate_header()
    word=['.syntax unified','mov r1,r0','1: ldrb r2,[r0]','cmp r2,#0','beq 9f','lsls r3,r0,#30','beq 2f','adds r0,#1','b 1b','2: push {r4,r5}','ldr r4,10f','lsls r5,r4,#7','3:']
    word+=['.rept 1']
    text=asm(word)+('#if MK61_M0_LIBC_CURRENT == 16\n'+asm(['ldmia r0!,{r2}','subs r3,r2,r4','bics r3,r2','tst r3,r5','bne 4f'])+'#endif\n')
    text+=asm(['ldmia r0!,{r2}','subs r3,r2,r4','bics r3,r2','tst r3,r5','bne 4f','.endr','b 3b','4: subs r0,#4','5: uxtb r3,r2','cmp r3,#0','beq 6f','lsrs r2,#8','adds r0,#1','b 5b','6: subs r0,r0,r1','pop {r4,r5}','bx lr','9: subs r0,r0,r1','bx lr','.p2align 2','10: .word 0x01010101'])
    (ROOT/'code/libc_m0_strlen_word.inc').write_text('/* Aligned containing-word search; no prefix read. */\n'+text)
    patch=(ROOT/'research/memcmp-2026-10-21/evidence/m0-prepared/prototype.patch').read_text();part=patch.split('diff --git a/code/memcmp_m0.inc b/code/memcmp_m0.inc\n',1)[1].split('\ndiff --git ',1)[0]
    body='\n'.join(s[1:] for s in part.splitlines() if s.startswith('+') and not s.startswith('+++'))+'\n'
    old='"mk61_compare_compare body,16\\n"';assert body.count(old)==1
    body=body.replace(old,'#if MK61_M0_LIBC_CURRENT == 8\n"mk61_compare_compare body,1\\n"\n#else\n'+old+'\n#endif')
    (ROOT/'code/libc_m0_memcmp_word.inc').write_text(body)
    print('Generated all eight opt-in bodies, three byte profiles and two word profiles')
if __name__=='__main__':main()
