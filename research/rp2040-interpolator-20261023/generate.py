#!/usr/bin/env python3
"""Generate integer-certified Q31 interpolation endpoints and frozen Q32 control."""
import argparse
from fractions import Fraction
import hashlib
import json
from math import isqrt
from pathlib import Path

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]

def root_seed(num,den,bits):
    n=(1<<(2*bits))*den
    q=isqrt(n//num)
    midpoint=num*(2*q+1)**2
    if 4*n>midpoint or (4*n==midpoint and q&1):q+=1
    assert num*(2*q-1)**2<4*n<num*(2*q+1)**2
    return q

def generate():
    linear=[[root_seed((256+j)<<p,256,31) for j in range(257)] for p in range(2)]
    def sqrt_endpoint(num,den):
        n=num<<62;q=isqrt(n//den)
        if 4*n>den*(2*q+1)**2 or (4*n==den*(2*q+1)**2 and q&1):q+=1
        return min((1<<32)-1,q)
    roots=[[sqrt_endpoint((256+j)<<p,256) for j in range(257)] for p in range(2)]
    current=[root_seed((513+2*j)<<p,512,32) for p in range(2) for j in range(256)]
    # Each seed stays constant throughout one index+alpha subcell. Endpoints
    # enclose every exact m, including all unexamined low 36 mantissa bits.
    # z = M*(seed/2^31)^2 has denominator 2^114 for M=m*2^p/2^52.
    one=1<<114;worst=0;witness=None;root_initial_error=0;inverse_initial_error=0
    for p in range(2):
      for j in range(256):
        a,b=linear[p][j:j+2]
        for alpha in range(256):
          s=a-(((a-b)*alpha+255)>>8)
          lo=(1<<52)+(j<<44)+(alpha<<36);hi=lo+(1<<36)
          distance=max(abs((lo<<p)*s*s-one),abs((hi<<p)*s*s-one))
          if distance>worst:worst,witness=distance,[p,j,alpha,s]
          ra,rb=roots[p][j:j+2];r=ra+((rb-ra)*alpha>>8)
          root_initial_error=max(root_initial_error,abs(r-isqrt(lo<<(10+p)))+1,abs(r-isqrt(hi<<(10+p)))+1)
          inverse_initial_error=max(inverse_initial_error,abs(s-isqrt(one//(lo<<p)))+1,abs(s-isqrt(one//(hi<<p)))+1)
    eps=Fraction(worst,one)
    assert eps<Fraction(1,16)
    # For |z-1|<=eps<1/16, Newton's relative error is bounded by eps^2.
    # The root is <=1; thus absolute Q31 error <=2^31*eps^2. Rounded
    # square/product/correction add <=3 Q31 units. Flooring M to Q30 adds
    # <1 Q31 unit. Converting to Q32 and comparison to RNE add <=1 unit.
    bound=2*(4+(1<<31)*eps*eps)+1
    assert bound<13,(float(bound),witness)
    # Root correction uses the unrefined inverse. If delta is the initial
    # root error and eta the inverse error, the corrected error is exactly
    # -delta*sqrt(M)*eta-delta^2*v/2. sqrt(M)<=2 and v<=1. The integer
    # correction contributes <=1/2+2^-31; RNE oracle contributes <=1/2.
    root_bound=Fraction(2*root_initial_error*inverse_initial_error,1<<31)+Fraction(root_initial_error**2,1<<32)+1+Fraction(1,1<<31)
    assert root_bound<11,float(root_bound)
    text='// Generated by generate.py. All endpoints certified with exact integers.\n'
    text+='static const uint32_t linear_rsqrt_seeds[2][257]={\n'
    for row in linear:text+='  {'+','.join(str(v)+'U' for v in row)+'},\n'
    text+='};\nstatic const uint32_t current_rsqrt_seeds[512]={\n'
    for j in range(0,len(current),8):text+='  '+','.join(str(v)+'U' for v in current[j:j+8])+',\n'
    text+='};\n'
    text+='static const uint32_t linear_sqrt_seeds[2][257]={\n'
    for row in roots:text+='  {'+','.join(str(v)+'U' for v in row)+'},\n'
    text+='};\n'
    source=ROOT/'code/native_eabi_m0_pow_fast.inc'
    old_table=ROOT/'code/native_eabi_m0_rsqrt_table.inc'
    import re
    assert [int(v) for v in re.findall(r'(\d+)U,',old_table.read_text())]==current
    return text,dict(status='PASS',subcells=2*256*256,rsqrt_table_bytes=2*257*4,sqrt_pair_table_bytes=4*257*4,
      exact_endpoint_checks=1540,epsilon_numerator=str(worst),epsilon_denominator=str(one),
      epsilon=float(eps),seed_error_bound_q32=float(bound),required_bound_q32=13,
      sqrt_root_error_bound_q31=float(root_bound),sqrt_inverse_error_bound_q31=float(bound/2),
      initial_root_error_q31=root_initial_error,initial_inverse_error_q31=inverse_initial_error,
      proof='Monotone exact M bounds within every alpha cell; analytic Newton/rounding bound, not random sampling.',
      witness=witness,reference_sha256={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in (source,old_table)})

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    text,report=generate();dest=HERE/'tables.inc'
    root_table=(ROOT/'code/native_eabi_m0_sqrt64_table.inc').read_text()
    if a.check:
      assert dest.read_text()==text
      assert (HERE/'baseline_sqrt_table.inc').read_text()==root_table
    else:
      dest.write_text(text)
      (HERE/'baseline_sqrt_table.inc').write_text(root_table)
    (HERE/'seed-certificate.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
if __name__=='__main__':main()
