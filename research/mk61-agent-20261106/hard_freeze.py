def signed(expr):return isinstance(expr,list)and(expr[0]in['abs','neg']or any(signed(x)for x in expr[1:]))


def task(expr,text,rng,index,split,em):
    code=compile_expr(expr)+[0x50];cases=[]
    while len(cases)<9:
        values=[-15,-7,-3,-1,0,1,3,5,9,16]if signed(expr)else[1,2,3,4,6,8,11,14,18,23]
        regs={r:rng.choice(values)for r in sorted(registers_used(expr))}
        try:v=value_of(expr,regs)
        except ArithmeticError:continue
        if not v.is_finite()or abs(v)>1e6 or(not signed(expr)and v<0):continue
        case={'registers':regs,'expected_X':str(v.normalize())}
        if check_program(em,code,[case])['pass']:cases.append(case)
    return {'id':f'{split}:{index}','kind':'natural_language','task':text+' Входные данные уже в регистрах МК-61. Результат оставь в X и остановись С/П.',
            'expression':expr,'family':family_of(expr),'reference_code':code,'public_tests':cases[:2],'hidden_tests':cases[2:]}


def main():
    root=BUILD/'distill-hard';root.mkdir(exist_ok=True)
    if(root/'frozen.json').exists():raise SystemExit('Hard continuation audit already frozen')
    rng=random.Random(6110611);em=Emulator();manifest={'created_before_new_gradients':True,'fresh_audit_used_for_training_or_selection':False,
         'fresh_audit_design':'32 calculation specifications with two independently phrased conditions each; 64 conditions, not 64 novel algorithm families','files':{}}
    rows=[]
    for expr,a,b in AUDIT:
        for text in[a,b]:rows.append(task(expr,text,rng,len(rows),'hard-fresh',em))
    save_jsonl(root/'fresh-russian.jsonl',rows)
    val=[task(e,t,rng,i,'hard-validation',em)for i,(e,t)in enumerate(VALIDATION)]
    old=[json.loads(x)for x in(BUILD/'distill-v1/validation-v2.jsonl').read_text().splitlines()]
    formal=[json.loads(x)for x in(BUILD/'tasks/validation-extended-v2.jsonl').read_text().splitlines()]
    controls=[t for t in formal if t['kind']in['branch','loop','state']]
    save_jsonl(root/'selection.jsonl',old+val+formal[:8]+controls)
    for name in ['fresh-russian.jsonl','selection.jsonl']:
        p=root/name;manifest['files'][name]={'rows':len(p.read_text().splitlines()),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}
    (root/'frozen.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n');print(json.dumps(manifest,indent=2))


