def main():
    root=BUILD/'native-mixed-v1';root.mkdir(exist_ok=True)
    if(root/'frozen.json').exists():raise SystemExit('Frozen files already exist')
    rng=random.Random(6111601);em=Emulator();rows=[]
    old=BUILD/'capacity-v1'
    seen={normalize(r['task'])for file in ['level1-validation-manual.jsonl','level1-fresh.jsonl']for r in read_tasks(old/file)}
    teacher=read_tasks(old/'server-results/course-level1/train.jsonl');seen.update(normalize(r['task'])for r in teacher)
    for op,templates in FRESH.items():
        for i,text in enumerate(templates):
            a,b=rng.sample(['R0','R1','R2','R3'],2);text=text.format(a=a,b=b)
            if normalize(text)in seen:raise ValueError('Audit wording overlaps observed data: '+text)
            expr=[op,a,b]if op in ['+','-','*','/']else[op,a]
            rows.append(make_task(text,expr,rng,f'native-fresh:{op}:{i}',level=1,split='fresh',emulator=em))
    save_jsonl(root/'fresh-level1.jsonl',rows)
    # All these panels are already observed. They remain development, never a
    # new independent audit and never newly added gradient targets.
    manual=read_tasks(old/'level1-validation-manual.jsonl')+read_tasks(old/'level1-fresh.jsonl')
    save_jsonl(root/'development-manual.jsonl',manual)
    for level in [2]:
        for source,target in [(f'level{level}-validation-manual.jsonl',f'development-level{level}.jsonl'),
                              (f'level{level}-fresh.jsonl',f'fresh-level{level}.jsonl')]:
            (root/target).write_bytes((old/source).read_bytes())
    files={p.name:{'rows':len(p.read_text().splitlines()),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}for p in root.glob('*.jsonl')}
    policy={'files':files,'before_new_teacher_or_gradients':True,'fresh_for_selection':False,
      'manual_level1_new_statements':84,'level2_probes_reused_from_previously_unopened_pool':True,
      'models':{'q4':5789568,'mixed':7509888},'language_tokens_each':100000000,'sft_steps_each':8000,
      'gate':'90% parsing and model-written program execution on observed manual and held-out teacher development, formal>=95%',
      'training_precision':'Q4 vsQ2 FFN/Q4 rest from first new update; learned per-group Q2 amplitude',
      'long_context':'Dedicated curriculum and probes up to2048; configuration alone is not a quality claim',
      'native_device_execution_measured':False}
    (root/'frozen.json').write_text(json.dumps(policy,ensure_ascii=False,indent=2)+'\n');print(json.dumps(policy),flush=True)


if __name__=='__main__':main()
