def make_task(text, expr, rng, index, split):
    # Positive values avoid impossible negative counts/lengths in word problems.
    # Signed quantities are additionally tested in the formal regression suite.
    from tasks import registers_used, value_of
    t = expression_task(expr, rng, index, split=split)
    t.pop("initial_code", None)
    t.update(id=f"{split}:{index}", kind="natural_language", task=text + " Вход уже в регистрах МК-61. Ответ в X, затем С/П.")
    cases = []
    while len(cases) < 9:
        registers = {r: rng.choice([1, 2, 3, 4, 5, 7, 9, 12, 15, 20]) for r in sorted(registers_used(expr))}
        try: value = value_of(expr, registers)
        except ArithmeticError: continue
        if value.is_finite() and abs(value) < 1000000:
            cases.append({"registers": registers, "expected_X": str(value.normalize())})
    t["public_tests"], t["hidden_tests"] = cases[:2], cases[2:]
    return t


def main():
    root=BUILD / "distill-v1"
    root.mkdir(parents=True,exist_ok=True)
    if (root/"frozen.json").exists():raise SystemExit("Distillation checks already frozen")
    rng=random.Random(6110601)
    em=Emulator()
    manifest={"test_used_for_training_or_selection":False,"created_before_teacher_generation":True,
              "purpose":"Natural Russian semantic transfer; elementary algorithm families may also occur in training",
              "authors":"Separately authored statements in freeze_distill.py, not teacher generated",
              "test_cases":"Two visible and seven hidden numerical cases per statement; positive source register values",
              "files":{}}
    for split,definitions in [("validation",VALIDATION),("fresh-russian",AUDIT)]:
        rows=[make_task(text,expr,rng,i,split) for i,(text,expr) in enumerate(definitions)]
        for row in rows:
            assert check_program(em,row["reference_code"],row["public_tests"]+row["hidden_tests"])["pass"], row["id"]
        path=root/(split+".jsonl");save_jsonl(path,rows)
        manifest["files"][path.name]={"rows":len(rows),"sha256":hashlib.sha256(path.read_bytes()).hexdigest()}
    manifest["success_target"]={"fresh_russian_q4_pass_rate":0.8,"formal_regression_q4_pass_rate":0.95}
    manifest["selection_policy"]="Highest Q4 pass rate on separately authored validation, with formal regression development guard; fresh test never used for checkpoint selection"
    (root/"frozen.json").write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+"\n")
    print(json.dumps(manifest,ensure_ascii=False,indent=2))


if __name__=="__main__":main()
