"""Inference-only, paired diagnostic: one WRITE after the first rejected DONE.

Does not update weights, the declared hypothesis, the checker, or the action budget.
The already opened BH exam is diagnostic data, not a new closed test.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import random
import time

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
PAIR = REPO / '.build/mk61-agent-20261106/spec-pairs-v1'
ROOT = PAIR.parent / 'done-rejected-write-v1'
ARMS = ['lora', 'full']


def read(path):
    return json.loads(path.read_text())


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')
    temporary.replace(path)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sources():
    return PAIR if (PAIR / 'export/fixed6000_lora/model.mkqb').exists() else PAIR / 'server-results'


def prepare():
    assert not (ROOT / 'protocol.json').exists(), 'Protocol already registered'
    src = sources()
    files = [src / 'closed-clean.jsonl', src / 'frozen.json']
    for arm in ARMS:
        files.append(src / f'fixed6000_{arm}/closed.json')
        folder = src / f'export/fixed6000_{arm}'
        files += [p for p in folder.rglob('*') if p.is_file()]
    value = {
        'kind': 'done-rejected-write-v1', 'registered_unix': time.time(),
        'inference_only': True, 'optimizer_updates': 0, 'model_selection': False,
        'dataset_status': 'post-hoc diagnostic on the already opened BH closed exam',
        'models': ['fixed6000_lora', 'fixed6000_full'], 'quantization': 'packed Q4',
        'compute_and_KV': 'FP32', 'context': 1024, 'max_turns': 12,
        'cohort_seed': 261110117, 'conditions': 256, 'episodes_per_branch_per_policy': 512,
        'initial_states': ['correct reference code', 'deterministic stopped but wrong mutant'],
        'control': 'ordinary neural loop with the unchanged self gate',
        'treatment': 'force WRITE on the next ordinary action after the first actual DONE_REJECTED, once per episode; all other actions neural',
        'all_rejection_reasons_included': True, 'extra_turns': 0,
        'forced_WRITE_body': 'generated by the same model from its ordinary current prompt',
        'WRITE_runs_current_public_case_as_in_original_runtime': True,
        'declared_initial_spec_and_checker_unchanged': True,
        'hidden_task_reference_only_for_offline_scoring': True,
        'no_automatic_RUN_or_DONE_after_the_forced_WRITE': True,
        'same_saved_initial_plans_for_both_policies': True,
        'control_rerun_and_compare_to_saved_original': True,
        'primary_metrics': ['wrong_starts_repaired', 'correct_starts_corrupted', 'false_DONE'],
        'driver_sha256': sha(Path(__file__)),
        'files': {str(p.relative_to(src)): sha(p) for p in sorted(files)},
    }
    write(ROOT / 'protocol.json', value)
    print(json.dumps({'registered': str(ROOT / 'protocol.json'), 'sha256': sha(ROOT / 'protocol.json')}))


def check_inputs():
    from bh_common import check_frozen
    check_frozen()
    protocol = read(ROOT / 'protocol.json')
    assert sha(Path(__file__)) == protocol['driver_sha256']
    src = sources()
    for name, digest in protocol['files'].items():
        accepted = [digest, *protocol.get('equivalent_remote_file_hashes', {}).get(name, [])]
        assert sha(src / name) in accepted, name
    return protocol


def episodes(model, tokenizer, goals, plans, vm, policy, arm):
    import ay_eval as core
    from aq_eval import generate
    from ar_spec import verify
    from az_runtime import Session
    from bh_common import MAX_TURNS
    assert MAX_TURNS == 12
    jobs = []
    for i, goal in enumerate(goals):
        kind, bad = core.mutant(goal, vm, ['operation', 'argument', 'order'][i % 3])
        jobs += [(goal, 'correct', goal['reference_body']), (goal, kind, bad)]
    records = []
    for at in range(0, len(jobs), 24):
        chunk = jobs[at:at + 24]
        sessions = []
        for goal, label, body in chunk:
            session = Session(goal, body, vm, 'spec', plans[goal['id']]['declared_spec'], True)
            session.recovery_used = False
            session.recovery_pending = False
            session.recovery_events = []
            session.first_rejection = None
            sessions.append(session)
        for turn in range(MAX_TURNS):
            active = [s for s in sessions if not s.finished and not s.abstained and not getattr(s, 'exhausted', False)]
            if not active:
                break
            prompts = [s.request() for s in active]
            # Keep the ordinary batched generation intact; replace only the
            # forced action's output. The extra forward pass is diagnostic cost.
            output = generate(model, tokenizer, prompts)
            forced = [j for j, s in enumerate(active) if policy == 'one_write' and s.recovery_pending and not s.recovery_used]
            if forced:
                replacement = generate(model, tokenizer, [prompts[j] for j in forced], forced_action='write')
                for j, value in zip(forced, replacement):
                    active[j].recovery_used = True
                    active[j].recovery_pending = False
                    active[j].recovery_events.append({'turn': turn, 'before_body': list(active[j].body), 'ordinary_action': output[j].get('action')})
                    output[j] = value
            for j, (session, prompt, value) in enumerate(zip(active, prompts, output)):
                is_forced = j in forced
                if value.get('codec_error'):
                    session.history.append({'kind': 'generation_error', 'prompt': prompt, 'generation': value})
                    session.exhausted = True
                else:
                    try:
                        result = session.apply_action(value['action'], value['body'])
                        if result == 'done_rejected':
                            if session.first_rejection is None:
                                session.first_rejection = {'turn': turn, 'body': list(session.body), 'check': session.gate_checks[-1]}
                            if not session.recovery_used:
                                session.recovery_pending = True
                    except (ValueError, ArithmeticError, RuntimeError) as error:
                        session.observation = 'ERROR ' + str(error)
                        session.history.append({'kind': 'error', 'observation': session.observation})
                    session.history[-1].update(prompt=prompt, generation=value)
                if is_forced:
                    session.history[-1]['forced_action'] = 'write'
                    session.recovery_events[-1].update(after_body=list(session.body), generation=value, history_index=len(session.history) - 1)
        for (goal, label, initial_body), session in zip(chunk, sessions):
            check = verify(vm, session.body, session.pool, goal['spec'], goal['audit_inputs'])
            correct = check['status'] == 'TESTED'
            eligible = session.eligibility()[0]
            spec = plans[goal['id']]['declared_spec']
            own = verify(vm, session.body, session.pool, spec, goal['audit_inputs'])
            for event in session.recovery_events:
                # Hidden labels are obtained only after the interaction ends.
                event['before_task_correct'] = verify(vm, event['before_body'], session.pool, goal['spec'], goal['audit_inputs'])['status'] == 'TESTED'
                event['after_task_correct'] = verify(vm, event['after_body'], session.pool, goal['spec'], goal['audit_inputs'])['status'] == 'TESTED'
            records.append({
                'id': goal['id'] + ':' + label, 'task_id': goal['id'], 'panel': goal['panel'], 'family': goal['family'],
                'initial': label, 'initially_correct': label == 'correct', 'gate': 'self', 'policy': policy,
                'program_correct': correct, 'spec_consistent': own['status'] == 'TESTED',
                'finished': session.finished, 'eligible': eligible, 'pass': bool(correct and session.finished and eligible),
                'abstained': session.abstained, 'body': session.body, 'initial_body': initial_body,
                'task_audit': check, 'declared_spec': spec, 'gate_checks': session.gate_checks, 'history': session.history,
                'first_rejection': session.first_rejection, 'recovery_used': session.recovery_used,
                'recovery_events': session.recovery_events,
            })
        write(ROOT / arm / 'status.json', {'phase': policy, 'completed': len(records), 'total': len(jobs), 'unix': time.time()})
        print(json.dumps({'arm': arm, 'policy': policy, 'completed': len(records), 'total': len(jobs)}), flush=True)
    return records


def rerun_check(records, saved):
    previous = {r['id']: r for r in saved}
    scalar_keys = ['program_correct', 'spec_consistent', 'finished', 'eligible', 'pass', 'abstained', 'body', 'declared_spec', 'gate_checks']
    differences = []
    for record in records:
        old = previous[record['id']]
        different = [k for k in scalar_keys if record[k] != old[k]]
        signature = lambda r: [(h['kind'], h.get('generation', {}).get('generated_token_ids'), h.get('prompt')) for h in r['history']]
        if signature(record) != signature(old):
            different.append('trajectory')
        if different:
            differences.append({'id': record['id'], 'fields': different})
    return {'episodes': len(records), 'exact_matches': len(records) - len(differences), 'differences': differences}


def paired(control, treatment):
    assert [r['id'] for r in control] == [r['id'] for r in treatment]
    result = {}
    for name, predicate in [
        ('wrong_starts_repaired', lambda r: not r['initially_correct'] and r['pass']),
        ('correct_starts_corrupted', lambda r: r['initially_correct'] and not r['program_correct']),
        ('false_DONE', lambda r: r['finished'] and not r['program_correct']),
        ('passed', lambda r: r['pass']),
    ]:
        gained = [b['id'] for a, b in zip(control, treatment) if not predicate(a) and predicate(b)]
        lost = [b['id'] for a, b in zip(control, treatment) if predicate(a) and not predicate(b)]
        result[name] = {'control': sum(map(predicate, control)), 'one_write': sum(map(predicate, treatment)),
                        'delta': len(gained) - len(lost), 'gained_ids': gained, 'lost_ids': lost}
    return result


def evaluate(arm):
    import torch
    from transformers import AutoTokenizer
    from native_verify import verify_export
    from bh_common import compact_head, output_ids
    from bh_spec import install
    import bh_eval  # installs the unchanged BH session/mutant on ay_eval
    import ay_eval as core
    from full_isa_vm import FullVM
    protocol = check_inputs()
    torch.set_num_threads(4)
    torch.backends.cuda.matmul.allow_tf32 = False
    install()
    src = sources()
    folder = src / f'export/fixed6000_{arm}'
    model, receipt = verify_export(folder)
    before = {n: hashlib.sha256(p.detach().cpu().contiguous().numpy().tobytes()).hexdigest() for n, p in model.named_parameters()}
    assert all(p.grad is None for p in model.parameters())
    tokenizer = AutoTokenizer.from_pretrained(folder / 'hf', local_files_only=True)
    model.cuda().eval()
    compact_head(model, output_ids(tokenizer))
    goals = [json.loads(line) for line in (src / 'closed-clean.jsonl').read_text().splitlines()]
    cohort = core.choose_runtime(goals, protocol['conditions'], protocol['cohort_seed'])
    original = read(src / f'fixed6000_{arm}/closed.json')
    plans = {r['id']: r for r in original['primary']['records']}
    started = time.monotonic()
    results = {}
    for policy in ['control', 'one_write']:
        records = episodes(model, tokenizer, cohort, plans, FullVM(), policy, arm)
        assert len(records) == 512
        results[policy] = {'summary': core.episode_metrics(records), 'records': records}
        write(ROOT / arm / (policy + '.json'), results[policy])
    check_inputs()
    after = {n: hashlib.sha256(p.detach().cpu().contiguous().numpy().tobytes()).hexdigest() for n, p in model.named_parameters()}
    assert before == after and all(p.grad is None for p in model.parameters())
    control = results['control']['records']
    treatment = results['one_write']['records']
    used = [r for r in treatment if r['recovery_used']]
    assert all(len(r['recovery_events']) <= 1 for r in treatment)
    nontriggered = [r for r in treatment if not r['recovery_used']]
    comparison = {
        'arm': arm, 'optimizer_updates': 0, 'weights_unchanged': True, 'export_verification': receipt,
        'protocol_sha256': sha(ROOT / 'protocol.json'), 'driver_sha256': sha(Path(__file__)),
        'model_mkqb_sha256': sha(folder / 'model.mkqb'), 'seconds': time.monotonic() - started,
        'control': results['control']['summary'], 'one_write': results['one_write']['summary'],
        'control_reproducibility': rerun_check(control, original['self']['records']),
        'paired': paired(control, treatment),
        'triggered': {
            'total': len(used), 'initially_correct': sum(r['initially_correct'] for r in used),
            'initially_wrong': sum(not r['initially_correct'] for r in used),
            'reasons': dict(collections.Counter(r['first_rejection']['check']['reason'] for r in used)),
            'ordinary_next_actions_replaced': dict(collections.Counter(r['recovery_events'][0]['ordinary_action'] for r in used)),
            'summary': core.episode_metrics(used),
            'immediate_WRITE_correct_code': sum(r['recovery_events'][0]['after_task_correct'] for r in used),
            'immediate_WRITE_corrupted_code': sum(r['recovery_events'][0]['before_task_correct'] and not r['recovery_events'][0]['after_task_correct'] for r in used),
            'generation_errors': sum(bool(r['recovery_events'][0]['generation'].get('codec_error')) for r in used),
        },
        'nontriggered_reproducibility': rerun_check(nontriggered, control),
        'posthoc_diagnostic': True, 'no_profile_change': True,
    }
    write(ROOT / arm / 'comparison.json', comparison)
    write(ROOT / arm / 'complete.json', {'complete': True, 'unix': time.time(), 'optimizer_updates': 0,
                                        'comparison_sha256': sha(ROOT / arm / 'comparison.json'), 'weights_unchanged': True})
    write(ROOT / arm / 'status.json', {'phase': 'complete', 'unix': time.time()})
    print(json.dumps({k: v for k, v in comparison.items() if k not in ['paired']}, ensure_ascii=False), flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=['prepare', 'evaluate'])
    parser.add_argument('--arm', choices=ARMS)
    args = parser.parse_args()
    if args.action == 'prepare':
        prepare()
    else:
        assert args.arm is not None
        evaluate(args.arm)
