"""Build and prove a table of coprime moduli for the bounded comparator."""

import argparse
from itertools import accumulate
from math import factorial, gcd
from pathlib import Path


RADIX = 1 << 32
MODULI = 4608
OFFSET_LIMIT = 1 << 16


def offsets_near_radix():
    """Choose coprime odd moduli, initially skipping factors up to 500."""
    used_factors = factorial(500)
    offsets = []
    for offset in range(1, OFFSET_LIMIT, 2):
        modulus = RADIX-offset
        if gcd(used_factors, modulus) == 1:
            offsets.append(offset)
            if len(offsets) == MODULI:
                break
            used_factors *= modulus
    return tuple(offsets)


def table():
    offsets = offsets_near_radix()
    gaps = tuple(b-a for a, b in zip((0, *offsets), offsets))
    assert len(offsets) == MODULI and all(0 < gap <= 255 for gap in gaps)
    assert offsets[-1] < OFFSET_LIMIT and tuple(accumulate(gaps)) == offsets
    # Bernoulli's product inequality gives P > 2**(32*n-1) for every prefix.
    assert 2*sum(offsets) < RADIX
    prefix, inverse = 1, []
    for offset in offsets:
        modulus = RADIX-offset
        factor = pow(prefix, -1, modulus)
        assert prefix*factor % modulus == 1
        inverse.append(factor)
        prefix *= modulus
    assert prefix.bit_length() == 32*MODULI
    # A narrow fold starts below 2**48. One fold is below twice
    # its modulus, including both ends of the allowed offset range.
    assert RADIX-1+(OFFSET_LIMIT-1)**2 < 2*(RADIX-(OFFSET_LIMIT-1))
    return offsets, gaps, inverse


def emit(path):
    _, gaps, inverse = table()
    with path.open('w', encoding='ascii') as out:
        print('// Generated by coprime_residue_table.py.', file=out)
        for name, typ, values, columns in (
                ('ModulusGaps', 'uint8_t', gaps, 16), ('PrefixInverse', 'uint32_t', inverse, 8)):
            print(f'static constexpr {typ} {name}[{MODULI}] = {{', file=out)
            for start in range(0, len(values), columns):
                print('    '+', '.join(f'{v}U' for v in values[start:start+columns])+',', file=out)
            print('};', file=out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=Path)
    emit(parser.parse_args().header)
