#!/usr/bin/env python3
"""Generate independent binary64 exponential reduction/table constants."""
from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    with localcontext() as context:
        context.prec = 100
        step = Decimal(2).ln() / 512
        c = step * (1 << 64)
        high = int(c)
        low = int(((c-high)*(1 << 32)).to_integral_value(rounding=ROUND_HALF_EVEN))
        values = [int(((step*i).exp()*(1 << 62)).to_integral_value(rounding=ROUND_HALF_EVEN))
                  for i in range(512)]
        # Raising each half-integer rounding interval to the 512th power
        # checks all table roundings using integers, independent of Decimal.
        for i,v in enumerate(values):
            exact = 1 << (63*512+i)
            assert (2*v-1)**512 < exact < (2*v+1)**512
        # ln(2)=2*atanh(1/3), with a positive geometrically bounded tail.
        # This independently certifies the split reduction constant and
        # the Q31 reciprocal used to choose the nearest table segment.
        lower = sum((Fraction(2,(2*i+1)*3**(2*i+1)) for i in range(100)),Fraction(0))
        upper = lower+Fraction(2,201*3**201)*Fraction(9,8)
        combined = (high << 32)+low
        assert Fraction(2*combined-1,2) < lower*(1 << 87)
        assert upper*(1 << 87) < Fraction(2*combined+1,2)
        reciprocal = 0xB8AA3B29
        assert Fraction(2*reciprocal-1,2) < (1 << 31)/upper
        assert (1 << 31)/lower < Fraction(2*reciprocal+1,2)
    target = ROOT / 'code/native_eabi_m0_exp_table.inc'
    target.write_text('// Generated by tools/generate_m0_exp_table.py; project-owned data.\n'
                      f'static constexpr U exp_step_high=UINT64_C({high});\n'
                      f'static constexpr uint32_t exp_step_low={low}U;\n'
                      'static constexpr U exp_table[512]={\n' +
                      ''.join(f'  UINT64_C({v}),\n' for v in values) + '};\n')


if __name__ == '__main__':
    main()
