#!/usr/bin/env python3
"""Generate independent quadratic sqrt coefficients for the ARMv6-M kernel."""
from decimal import Decimal, localcontext, ROUND_HALF_EVEN, ROUND_CEILING
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def coefficients():
    # sqrt(N)*256 on 64 segments per exponent parity, -1/2 <= t < 1/2.
    # Verify every rounded coefficient with integer inequalities, so the
    # generated words do not depend on Decimal's last computed digits.
    with localcontext() as context:
        context.prec=100
        for index in range(128):
            step=1<<(25 if index<64 else 24)
            middle=(2*(64+(index&63))+1)*(step//2)
            root=Decimal(middle).sqrt()
            values=(256*root,128*Decimal(step)/root,
                -32*Decimal(step)**2/(middle*root))
            # Rounding c0 upward offsets the final arithmetic-shift bias
            # without an extra instruction in the kernel.
            rounded=tuple(int(x.to_integral_value(rounding=ROUND_CEILING if i==0 else ROUND_HALF_EVEN))
                for i,x in enumerate(values))
            squares=((middle*(1<<16),1),((128*step)**2,middle),
                ((32*step*step)**2,middle**3))
            for i,(value,(numerator,denominator)) in enumerate(zip(rounded,squares)):
                n=abs(value)
                if i==0:assert (n-1)**2*denominator<numerator<=n*n*denominator
                else:assert (2*n-1)**2*denominator<4*numerator<(2*n+1)**2*denominator
            yield rounded


def main():
    target=ROOT/'code/native_eabi_m0_sqrt_table.inc'
    text='// Generated by tools/generate_m0_sqrt_table.py; project-owned data.\n'
    text+='// Three Taylor coefficients and padding per midpoint; c0 rounds up.\n'
    text+='// Each rounding is checked using exact integer square inequalities.\n'
    text+=''.join(' .word '+','.join(str(x) for x in (*row,0))+'\n' for row in coefficients())
    target.write_text(text)
    print(target.relative_to(ROOT))


if __name__=='__main__':main()
