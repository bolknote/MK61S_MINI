#!/usr/bin/env python3
"""Generate exact RNE Q32 inverse-square-root seeds at dyadic centers."""
import argparse
from math import isqrt
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def values():
    out=[]
    for parity in range(2):
        for j in range(256):
            numerator=(513+2*j)<<parity;denominator=512
            a=(1<<64)*denominator
            q=isqrt(a//numerator)
            middle=numerator*(2*q+1)**2
            if 4*a>middle or (4*a==middle and q&1):q+=1
            assert numerator*(2*q-1)**2<4*a<numerator*(2*q+1)**2
            out.append(q)
    return out


def render():
    return ('// Generated by tools/generate_m0_rsqrt_table.py; exact integer RNE certificates.\n'
            'static constexpr uint32_t pow_rsqrt_seeds[512]\n'
            '__attribute__((section(".m0_pow_extension_data"),aligned(4)))={\n'+
            ''.join('  '+str(q)+'U,\n' for q in values())+'};\n')


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    a=p.parse_args();path=ROOT/'code/native_eabi_m0_rsqrt_table.inc';text=render()
    if a.check:assert path.read_text()==text
    else:path.write_text(text)
    print('PASS:512 exact RNE inverse-root seed cells')


if __name__=='__main__':main()
