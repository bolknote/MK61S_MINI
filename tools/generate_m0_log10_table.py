#!/usr/bin/env python3
"""Generate the packed reciprocal/direct-log10 Q70 table by rational bounds."""
import argparse
from fractions import Fraction as F

from generate_m0_log10_constants import ROOT, bounds
from generate_m0_log_table import nearest


def log_bounds(x):
    t = (x-1)/(x+1)
    power, total = t, F(0)
    for j in range(100):
        total += 2*power/(2*j+1)
        power *= t*t
    return total, total+2*power/(201*(1-t*t))


def render():
    ln10lo, ln10hi = bounds()

    def value(x):
        lo, hi = log_bounds(x)
        q = nearest(lo*(1 << 70)/ln10hi)
        assert q == nearest(hi*(1 << 70)/ln10lo)
        return q

    rows = []
    for j in range(1024):
        center = F(2049+2*j, 2048)
        reciprocal = int(F(1 << 64)/center) & ~63
        q = value(center)
        assert q >> 64 < 64
        row = [(reciprocal & 0xFFFFFFFF) | (q >> 64), reciprocal >> 32,
               q & 0xFFFFFFFF, (q >> 32) & 0xFFFFFFFF]
        rows.append('  {'+','.join(str(n)+'U' for n in row)+'},\n')
    two = value(F(2))
    attr = ' __attribute__((section(".m0_math_extension_data")))'
    return ('// Generated by tools/generate_m0_log10_table.py; exact rational enclosures.\n'
            f'static constexpr U log10_two_low{attr}=UINT64_C({two&((1<<64)-1)});\n'
            f'static constexpr uint32_t log10_two_high{attr}={two>>64}U;\n'
            f'static constexpr uint32_t log10_table[1024][4]{attr}='+'{\n'+''.join(rows)+'};\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    target = ROOT/'code/native_eabi_m0_log10_table.inc'
    expected = render()
    if args.check:
        assert target.read_text() == expected, 'Regenerate the direct log10 table'
    else:
        target.write_text(expected)
    print('PASS: 1024 packed reciprocal/log10 rows, 16384 bytes')


if __name__ == '__main__':
    main()
