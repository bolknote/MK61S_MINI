#!/usr/bin/env python3
"""Generate independent Q62 coefficients and atan grid; mpmath is dev-only.

Polynomial constants use exact rational arithmetic. Transcendental constants
are rounded at 400 and 450 decimal digits and must agree before publication.
No Qfplib/emFloat source or tables are copied.
"""
from fractions import Fraction
from math import factorial
from pathlib import Path
import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]

def nearest_even(number):
    q, r = divmod(number.numerator, number.denominator)
    return q + (2*r > number.denominator or
                (2*r == number.denominator and q & 1))

def rational(denominator):
    return nearest_even(Fraction(1 << 62, denominator))

def transcendental(function):
    values = []
    for precision in (400, 450):
        with mp.workdps(precision):
            values.append(int(mp.nint(function() * mp.mpf(2)**62)))
    assert values[0] == values[1]
    return values[0]

def array(name, values, signed=True):
    suffix = "LL" if signed else "ULL"
    output = "static constexpr " + ("int64_t" if signed else "uint64_t")
    output += " " + name + "[] = {\n"
    for i in range(0, len(values), 4):
        output += "  " + ", ".join(str(v) + suffix for v in values[i:i+4]) + ",\n"
    return output + "};\n"

text = """// Generated by tools/generate_compact_math_tables.py; exact mathematical constants.
// Atan table/half pi: 400/450 decimal digits agree before rounding to Q62.
#pragma once
#include <stdint.h>
namespace compact_math { namespace tables {
"""
text += array("sine_coefficients", [(-1)**n*rational(factorial(2*n+1)) for n in range(9)])
text += array("cosine_coefficients", [(-1)**n*rational(factorial(2*n)) for n in range(10)])
text += array("exponential_coefficients", [rational(factorial(n)) for n in range(16)])
text += array("atan_coefficients", [(-1)**n*rational(2*n+1) for n in range(5)])
text += array("angle_table", [transcendental(lambda i=i: mp.atan(mp.mpf(i)/64)) for i in range(65)], False)
text += "static constexpr uint64_t half_pi = " + str(transcendental(lambda: mp.pi/2)) + "ULL;\n"
# Payne-Hanek phase: a 1600-bit prefix, independently agreed at 600/650 digits.
phase = []
for precision in (600, 650):
    with mp.workdps(precision):
        phase.append(int(mp.floor((2/mp.pi) * mp.mpf(2)**1600)))
assert phase[0] == phase[1]
text += "// Little-endian 2/pi fixed-point digits, K=1600; 600/650 digits agree.\n"
text += "static constexpr uint32_t two_over_pi[] = {\n"
for i in range(0, 50, 5):
    values = [(phase[0] >> (32*j)) & 0xFFFFFFFF for j in range(i, min(i+5, 50))]
    text += "  " + ", ".join(f"0x{x:08X}U" for x in values) + ",\n"
text += "};\n"
text += "} } // namespace compact_math::tables\n"
(ROOT/"code/compact_math_tables.hpp").write_text(text)
print("Q62 constants generated: exact rational coefficients, 65 independent atan grid points")
