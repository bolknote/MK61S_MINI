#!/usr/bin/env python3
"""Generate the exact Q1024 floor of ln2 for the M0 pow refinement."""
import argparse
from fractions import Fraction
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def bounds():
    terms=500
    lower=sum((Fraction(2,(2*i+1)*3**(2*i+1)) for i in range(terms)),Fraction(0))
    upper=lower+Fraction(2,(2*terms+1)*3**(2*terms+1))*Fraction(9,8)
    return lower,upper


def render():
    lower,upper=bounds();scale=1<<1024
    value=(lower*scale).__floor__()
    assert value==(upper*scale).__floor__()
    words=[(value>>(16*i))&65535 for i in range(64)]
    return ('// Generated by tools/generate_m0_pow_interval_table.py; exact rational bounds.\n'
        'static constexpr uint16_t ln2_1024[64]={\n'+
        ''.join('  '+','.join(str(v)+'U' for v in words[i:i+8])+',\n' for i in range(0,64,8))+'};\n')


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=ROOT/'code/native_eabi_m0_pow_interval_table.inc')
    p.add_argument('--check',action='store_true')
    a=p.parse_args();text=render()
    if a.check:assert a.output.read_text()==text,'Regenerate the pow ln2 table'
    else:a.output.write_text(text)
    print('PASS exact rational pow ln2 table')


if __name__=='__main__':main()
