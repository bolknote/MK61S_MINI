#!/usr/bin/env python3
"""Independent Q94 tables for the M0 interval refinement, with certificates."""
from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from fractions import Fraction
from pathlib import Path
from generate_m0_log_table import logarithm,nearest

ROOT=Path(__file__).resolve().parents[1]


def main():
    def atan_bounds(x):
        if x>Fraction(1,2):
            a,b=atan_bounds(Fraction(1,2));c,d=atan_bounds((2*x-1)/(2+x));return a+c,b+d
        terms=120
        total=sum(((-1)**i*x**(2*i+1)/(2*i+1) for i in range(terms)),Fraction(0))
        return total,total+x**(2*terms+1)/(2*terms+1)
    def certified_round(lo,hi,precision):
        if lo==hi==0:return 0
        q=nearest((lo+hi)*(1<<(precision-1)))
        assert Fraction(2*q-1,2)<lo*(1<<precision)
        assert hi*(1<<precision)<Fraction(2*q+1,2)
        return q
    lower=sum((Fraction(2,(2*i+1)*3**(2*i+1)) for i in range(120)),Fraction(0))
    upper=lower+Fraction(2,241*3**241)*Fraction(9,8)
    with localcontext() as c:
        c.prec=120
        step=Decimal(2).ln()/512
        split=int((step*(1<<112)).to_integral_value(rounding=ROUND_HALF_EVEN))
        assert Fraction(2*split-1,2)<lower*(1<<103)
        assert upper*(1<<103)<Fraction(2*split+1,2)
        exps=[]
        for i in range(512):
            q=int(((step*i).exp()*(1<<94)).to_integral_value(rounding=ROUND_HALF_EVEN))
            exact=1<<(95*512+i)
            assert (2*q-1)**512<exact<(2*q+1)**512
            exps.append(q)
    target=ROOT/'code/native_eabi_m0_refine_table.inc'
    logs=[]
    for j in range(1024):
        center=Fraction(2049+2*j,2048)
        logs.append((nearest(Fraction(1<<94)/center),logarithm(center,94)))
    two=logarithm(Fraction(2),94)
    angles=[certified_round(*atan_bounds(Fraction(j,64)),70) for j in range(65)]
    a,b=atan_bounds(Fraction(1,5));c,d=atan_bounds(Fraction(1,239))
    half_pi=certified_round(8*a-2*d,8*b-2*c,70)
    inverses=[0]+[nearest(Fraction((1<<32)*4096,4096+j*j)) for j in range(1,65)]
    target.write_text('// Generated by tools/generate_m0_refine_tables.py; rational rounding certificates.\n'
        'static constexpr U refine_exp_step[2]={UINT64_C('+str(split&((1<<64)-1))+'),UINT64_C('+str(split>>64)+')};\n'
        'static constexpr uint32_t refine_exp_table[512][3]={\n'+
        ''.join('  {'+','.join(str((q>>(32*j))&0xFFFFFFFF)+'U' for j in range(3))+'},\n' for q in exps)+'};\n'+
        'static constexpr U refine_log_two_low=UINT64_C('+str(two&((1<<64)-1))+');\n'
        'static constexpr uint32_t refine_log_two_high='+str(two>>64)+'U;\n'
        'static constexpr uint32_t refine_log_table[1024][6]={\n'+
        ''.join('  {'+','.join(str((q>>(32*j))&0xFFFFFFFF)+'U' for q in row for j in range(3))+'},\n' for row in logs)+'};\n'+
        'static constexpr uint32_t refine_atan_half_pi[3]={'+','.join(str((half_pi>>(32*j))&0xFFFFFFFF)+'U' for j in range(3))+'};\n'
        'static constexpr uint32_t refine_atan_table[65][3]={\n'+
        ''.join('  {'+','.join(str((q>>(32*j))&0xFFFFFFFF)+'U' for j in range(3))+'},\n' for q in angles)+'};\n'+
        'static constexpr uint32_t refine_atan_inverse[65]={'+','.join(str(q)+'U' for q in inverses)+'};\n')


if __name__=='__main__':main()
