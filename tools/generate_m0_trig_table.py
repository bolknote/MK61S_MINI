#!/usr/bin/env python3
"""Generate project-owned sin/cos(j/1024) Q62 tables with exact certificates."""
from decimal import Decimal, localcontext, ROUND_HALF_EVEN
from fractions import Fraction
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def interval(x, cosine):
    term=Fraction(1) if cosine else x
    total=term
    for n in range(1,20):
        term=-term*x*x/((2*n-1 if cosine else 2*n)*(2*n if cosine else 2*n+1))
        total+=term
    next_term=-term*x*x/((39 if cosine else 40)*(40 if cosine else 41))
    return total,total+next_term


def values():
    with localcontext() as context:
        context.prec=100
        for j in range(806):
            x=Fraction(j,1024)
            row=[]
            for cosine in (False,True):
                lower,upper=interval(x,cosine)
                middle=(lower+upper)/2
                v=int((Decimal(middle.numerator)/Decimal(middle.denominator)*(1<<62)).to_integral_value(rounding=ROUND_HALF_EVEN))
                assert Fraction(2*v-1,2)<lower*(1<<62)
                assert upper*(1<<62)<Fraction(2*v+1,2)
                row.append(v)
            yield tuple(row)


def main():
    def atan_interval(q,n):
        total=sum((Fraction((-1)**i,(2*i+1)*q**(2*i+1)) for i in range(n)),Fraction(0))
        return total,total+Fraction(1,(2*n+1)*q**(2*n+1))
    a,b=atan_interval(5,80);c,d=atan_interval(239,20)
    lower,upper=16*a-4*d,16*b-4*c
    lo,hi=lower*(1<<190),upper*(1<<190)
    pi2=lo.numerator//lo.denominator
    assert pi2==hi.numerator//hi.denominator
    reciprocal_lo=(2<<32)/upper;reciprocal_hi=(2<<32)/lower
    assert reciprocal_lo.numerator//reciprocal_lo.denominator==0xA2F9836E
    assert reciprocal_hi.numerator//reciprocal_hi.denominator==0xA2F9836E
    target=ROOT/'code/native_eabi_m0_trig_table.inc'
    target.write_text('// Generated by tools/generate_m0_trig_table.py; project-owned data.\n'
        '// Every rounding certified by rational alternating-series bounds.\n'
        'static constexpr uint32_t trig_pi2[6]={'+','.join(str((pi2>>(32*i))&0xFFFFFFFF)+'U' for i in range(6))+'};\n'+
        'static constexpr U trig_table[806][2]={\n'+
        ''.join('  {'+','.join(f'UINT64_C({v})' for v in row)+'},\n' for row in values())+'};\n')


if __name__=='__main__':main()
