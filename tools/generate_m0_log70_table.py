#!/usr/bin/env python3
"""Certify the M0 Q70 log/reciprocal table by rational bounds."""
from fractions import Fraction
from pathlib import Path
from generate_m0_log_table import logarithm

ROOT=Path(__file__).resolve().parents[1]


def certificate():
    """Absolute Q70 bounds for the exact integer operations in log70.inc."""
    half=Fraction(1,2);scale=1<<70
    product46=Fraction(9,2)+Fraction(1,1<<14)
    product54=Fraction(17,32)+Fraction(1,1<<22)
    h=Fraction(1,2048)
    # |m-center| <= 2^41; the Q64 reciprocal is rounded down to 64.
    argument=product46+2
    assert h-Fraction(1,2049)>product46/scale
    square=1+Fraction(1,1<<16)
    cube=Fraction(35,64)+h*square
    seeded_h=Fraction(1,2049)+argument/scale
    assert scale*seeded_h<1<<59
    assert scale*seeded_h**2+square<1<<48
    third=half+cube/3
    fourth=1+63*h*64+scale*h**3/Fraction(1<<43)+h*cube
    fifth=1+h*fourth+scale*h**4/Fraction(1<<43)
    c=Fraction(52429,1<<18)
    fifth_term=c*fifth+max(2*c+(c-Fraction(1,5))*scale*h**5,1-2*c)
    remainder=scale*h**6/(6*(1-h))
    error=(argument/(1-h)+half+(half+square/2)+third+
           (half+fourth/4)+fifth_term+remainder)
    assert error<16

    # The near-one fast path sends the outer negative center to refine.
    # Remaining centers are >=8065/8192; distance <=2^48 in Q62.
    nh=Fraction(1,16000)
    near_argument=product54+Fraction(1,128)
    assert nh-Fraction(1,16130)>near_argument/scale
    nsquare=1+Fraction(1,1<<18)
    ncube=(half+nh*nsquare+
           (half*scale*nh/(1<<26)+half*(scale*nh*nh+nsquare)/(1<<13)+Fraction(1,4))/(1<<31))
    nthird=half+ncube/3
    # zr is rounded from z/2^13, then its square is rounded after >>44.
    nfourth=(half+(2*scale*nh*nh*nsquare+nsquare*nsquare)/scale+
             ((scale*nh*nh+nsquare)/(1<<13)+Fraction(1,4))/(1<<44))
    nremainder=scale*nh**5/(5*(1-nh))
    near_error=(near_argument/(1-nh)+half+(half+nsquare/2)+nthird+
                (half+nfourth/4)+nremainder)
    assert near_error<8
    return {
        'status':'PASS','rows':1024,'row_bytes':16,'table_bytes':16384,'rp2040_table_bytes':9216,'rp2040_residual_error':1,
        'product46_error':str(product46),'product54_error':str(product54),
        'main_error':str(error),'main_error_float':float(error),'main_enclosure':16,
        'near_error':str(near_error),'near_error_float':float(near_error),'near_enclosure':8,
        'arithmetic':'Exact rational propagation, all discarded products, fixed-point rounding, log series remainders and reciprocal/table quantization.'
    }


def main():
    proof=certificate()
    rows=[];lows=[];highs=[]
    for j in range(1024):
        center=Fraction(2049+2*j,2048)
        reciprocal=int(Fraction(1<<64)/center)&~63
        value=logarithm(center,70)
        assert value>>64<64 and not reciprocal&63
        fields=[(reciprocal&0xFFFFFFFF)|(value>>64),reciprocal>>32,
                value&0xFFFFFFFF,(value>>32)&0xFFFFFFFF]
        rows.append('  {'+','.join(str(q)+'U' for q in fields)+'},\n')
        lows.append(value&((1<<64)-1));highs.append(value>>64)
    two=logarithm(Fraction(2),70)
    (ROOT/'code/native_eabi_m0_log70_table.inc').write_text(
        '// Generated by tools/generate_m0_log70_table.py; exact rational certificates.\n'
        'static constexpr U log70_two_low=UINT64_C('+str(two&((1<<64)-1))+');\n'
        'static constexpr uint32_t log70_two_high='+str(two>>64)+'U;\n'
        '#if defined(MK61_M0_RP2040_EABI) && MK61_M0_RP2040_EABI\n'
        'static constexpr U log70_low[1024]={\n'+''.join('  UINT64_C('+str(v)+'),\n' for v in lows)+'};\n'
        'static constexpr uint8_t log70_high[1024]={\n'+''.join('  '+','.join(str(v)+'U' for v in highs[k:k+16])+',\n' for k in range(0,1024,16))+'};\n'
        '#else\nstatic constexpr uint32_t log70_table[1024][4]={\n'+''.join(rows)+'};\n#endif\n')
    return proof


if __name__=='__main__':main()
