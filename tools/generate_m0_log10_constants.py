#!/usr/bin/env python3
"""Generate reciprocal-ln(10) constants using exact rational enclosures."""
import argparse
from fractions import Fraction as F
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def atanh_bounds(t):
    lo = sum((2*t**(2*j+1)/(2*j+1) for j in range(160)), F(0))
    return lo, lo+2*t**321/(321*(1-t*t))


def bounds():
    # ln(10) = ln(5/4) + 3ln(2).
    a, b = atanh_bounds(F(1, 9))
    c, d = atanh_bounds(F(1, 3))
    return a+3*c, b+3*d


def constants():
    lo, hi = bounds()
    values = {}
    for precision in (64, 94):
        value = int((1 << precision)/hi)
        assert value == int((1 << precision)/lo)
        values[precision] = value
    return values


def render():
    values = constants()
    attr = ' __attribute__((section(".m0_math_extension_data")))'
    return ('// Generated by tools/generate_m0_log10_constants.py; exact rational bounds.\n'
            f'static constexpr U log10_inverse{attr}=UINT64_C({values[64]});\n'
            f'static constexpr Refine96 log10_inverse94{attr}='+'{'
            f'UINT64_C({values[94]&((1<<64)-1)}),{values[94]>>64}U'+'};\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    target = ROOT/'code/native_eabi_m0_log10_constants.inc'
    expected = render()
    if args.check:
        assert target.read_text() == expected, 'Regenerate the log10 constants'
    else:
        target.write_text(expected)
    print('PASS: exact reciprocal-ln(10) Q64/Q94 constants')


if __name__ == '__main__':
    main()
