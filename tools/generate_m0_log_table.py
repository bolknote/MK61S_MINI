#!/usr/bin/env python3
"""Certify project-owned Q62/Q70 logarithms and Q63/Q62 reciprocals."""
from fractions import Fraction
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def nearest(x):
    q,r=divmod(x.numerator,x.denominator)
    return q+int(2*r>x.denominator or (2*r==x.denominator and q&1))


def logarithm(x,precision=62):
    z=(x-1)/(x+1);power=z;total=Fraction(0)
    for i in range(100):
        total+=2*power/(2*i+1);power*=z*z
    upper=total+2*power/(201*(1-z*z))
    q=nearest(total*(1<<precision))
    assert Fraction(2*q-1,2)<total*(1<<precision)
    assert upper*(1<<precision)<Fraction(2*q+1,2)
    return q


def values():
    for j in range(256):
        c=Fraction(513+2*j,512)
        yield nearest(Fraction(1<<63)/c),logarithm(c)


def near_values():
    # The negative endpoint uses center 8065/8192, whose |ln| fits Q70
    # in uint64. The final result may carry into a 65th bit.
    for j in range(1,257):
        c=Fraction(8064+j,8192)
        row=nearest(Fraction(1<<62)/c),logarithm(c if c>=1 else 1/c,70)
        assert all(0<=value<1<<64 for value in row)
        yield row


def generated_source():
    text=('// Generated by tools/generate_m0_log_table.py; project-owned data.\n'
        '// Exact rational log-series bounds and reciprocal nearest rounding.\n'
        f'static constexpr U log_two=UINT64_C({logarithm(Fraction(2))});\n'
        'static constexpr U log_table[256][2]={\n'+
        ''.join('  {'+','.join(f'UINT64_C({v})' for v in row)+'},\n' for row in values())+'};\n'
        'static constexpr U log_near_table[256][2]={\n'+
        ''.join('  {'+','.join(f'UINT64_C({v})' for v in row)+'},\n' for row in near_values())+'};\n')

    from certify_m0_near77 import packed_source
    return packed_source(text)


def main():
    import argparse
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--target',type=Path,default=ROOT/'code/native_eabi_m0_log_table.inc')
    parser.add_argument('--check',action='store_true',help='Verify saved data without writing it')
    args=parser.parse_args();text=generated_source()
    if args.check:
        assert args.target.read_text()==text,'Generated logarithm table differs'
        print('Logarithm tables and packed RP2040 near-one data verified')
    else:args.target.write_text(text)


if __name__=='__main__':main()
