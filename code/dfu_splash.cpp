bool decode(u8* bitmap, usize capacity) {
  if(bitmap == nullptr || capacity < BYTE_COUNT) return false;
  Reader reader = {};
  const zx0::Input input = {&reader, read_byte};
  u32 written = 0;
  return zx0::decode(input, sizeof(PACKED_BITMAP), bitmap, BYTE_COUNT, written) &&
         written == BYTE_COUNT;
}

usize packed_byte_count(void) {
  return sizeof(PACKED_BITMAP);
}

